#!/usr/bin/env python3
"""Generate the export stubs and .def file for the D3d7Lib.dll proxy.

Reads src/exports.txt (the 76 exports of the original D3d7Lib.dll, in
ordinal order) and writes, into the output directory:
  stubs.h               - one tiny asm stub per export + name/vertex tables
  soulbringer_modern.def - export table mapping each name to its stub
"""
import os, sys

here = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'build')
os.makedirs(out, exist_ok=True)

names = [l.strip() for l in open(os.path.join(here, 'exports.txt')) if l.strip()]
assert len(names) == 76, f'expected 76 exports, got {len(names)}'

# Add* calls return a vertex buffer the game fills; for the debug log we
# need the vertex count, which follows from the third argument.
post = {'AddTri': '3*a2', 'AddTriStrip': 'a2+2', 'AddLine': '2*a2', 'AddDot': 'a2',
        'AddTriToOrderTable': '0', 'AddTriStripToOrderTable': '0', 'AddLineToOrderTable': '0',
        'AddDotToOrderTable': '0', 'AddPrim': '0', 'AddIndexedPrim': '0',
        'GetVertexBuffer': '0', 'LockVertexBuffer': '0'}

h = ['/* generated by src/gen_stubs.py - do not edit */',
     f'#define NFUNC {len(names)}',
     'static const char* const g_names[NFUNC]={%s};' % ','.join(f'"{n}"' for n in names),
     'static const unsigned char g_post[NFUNC]={%s};' % ','.join('1' if n in post else '0' for n in names),
     'static int vcount(int idx,const unsigned* a){switch(idx){']
for i, n in enumerate(names):
    if post.get(n, '0') != '0':
        h.append(f'case {i}: return (int)({post[n].replace("a2", "a[2]")});')
h.append('}return 0;}')
for i, n in enumerate(names):
    h.append(f'#define IDX_{n} {i}')
asm = ['.intel_syntax noprefix', '.text']
for i, n in enumerate(names):
    asm += [f'.globl _stub_{n}', f'_stub_{n}:', f'  push {i}', '  jmp _common_stub']
asm.append('.att_syntax prefix')
h.append('__asm__("%s");' % '\\n'.join(asm))
h += [f'void stub_{n}(void);' for n in names]
open(os.path.join(out, 'stubs.h'), 'w').write('\n'.join(h) + '\n')

with open(os.path.join(out, 'soulbringer_modern.def'), 'w') as f:
    f.write('LIBRARY D3d7Lib\nEXPORTS\n')
    for i, n in enumerate(names):
        f.write(f'  {n}=stub_{n} @{i+1}\n')
print(f'generated stubs for {len(names)} exports in {os.path.abspath(out)}')
